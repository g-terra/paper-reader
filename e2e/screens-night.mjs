// Night theme, contents panel, figure page and original-page view on an iPad.
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const require = createRequire(execSync('npm root -g').toString().trim() + '/');
const { chromium, devices } = require('playwright');
const out = process.argv[2] ?? '/tmp/screens';
const browser = await chromium.launch();
const c = await browser.newContext({ ...devices['iPad (gen 7) landscape'] });
const p = await c.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
await p.goto(process.env.APP_URL ?? 'http://localhost:5173/');
await p.evaluate(() => localStorage.setItem('paper-reader:settings', JSON.stringify({ theme: 'night' })));
await p.reload();
await p.locator('input[type=file]').setInputFiles(['fixtures/two-column-paper.pdf']);
await p.waitForFunction(() => document.body.innerText.includes('Added to your library'), null, { timeout: 600000 });
await p.getByRole('button', { name: 'Read', exact: true }).click();
await p.waitForTimeout(1200);
const vp = p.viewportSize();
await p.mouse.click(vp.width / 2, vp.height / 2);
await p.getByRole('button', { name: 'Contents' }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/night-toc.png` });
await p.getByRole('button', { name: /^Figure 1: Accuracy/ }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/night-figure.png` });
await p.getByRole('button', { name: 'Show original page' }).click();
await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/night-original.png` });
console.log(errors.length ? errors.join('\n') : 'no page errors');
await browser.close();
